package ascii

// GetCharacterHeight returns the height of each ASCII art character.
// In this case, each character is represented by 8 lines of ASCII art.
func GetCharacterHeight() int {
    return 8
}

// GetNumOfAsciiXters returns the total number of ASCII characters that the program can handle.
// In this case, the program can handle 95 different characters.
func  GetNumOfAsciiXters() int {
    return 95
}